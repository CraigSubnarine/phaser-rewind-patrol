// ---------- Bosses: big front views, each with two idle frames and a hurt pose ----------
// Drawn as the left half and mirrored (`sym`). `extras`, `idle` and `hurt` are layers painted over the base, as for
// compose() ([rows, column, row]); in them ',' erases to see-through. Frames: <key>0 and <key>1 (the idle animation)
// and <key>Hurt. All three are the same size, drawn at 6x.
const sym = rows => rows.map(r => r + [...r].reverse().join(''));
function bossArt(key, base, { extras = [], idle = [], hurt = [] } = {}) {
  const build = layers => compose(base[0].length, base.length, [[base, 0, 0], ...extras, ...layers]).map(r => r.replace(/,/g, '.'));
  Object.assign(ART, { [`${key}0`]: build([]), [`${key}1`]: build(idle), [`${key}Hurt`]: build(hurt) });
  for (const f of ['0', '1', 'Hurt']) PIXEL[`${key}${f}`] = 6;
}
